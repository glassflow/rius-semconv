"""Emits the Go constants file (`semconv_generated.go`).

The CANONICAL half of argus-core's semconv package only: every registry row
generated for Go, the span-kind values, the allowlists and the tables. The
normalizer's input spellings (llm.*, enduser.*, ai.prompt.tools, legacy
spellings) are not registry rows yet and stay in argus-core's hand-written
semconv.go, in the same package. See the README, "Go".

Go names are derived from the constant name unless the row overrides them
with `go:`. The derivation is deliberately boring, SNAKE_CASE to PascalCase
with a small initialism table, so a reviewer can predict a name from the
registry without running the generator.

The output is piped through gofmt, which owns alignment. gofmt is required:
emitting unaligned code when it is missing would make the output depend on
the machine that generated it.
"""

from __future__ import annotations

import json
import shutil
import subprocess

from .registry import Registry, comment

LANG = "go"
GENERATED = "// Code generated by rius-semconv. DO NOT EDIT."

INITIALISMS = {
    "ID": "ID",
    "GEN": "Gen",
    "AI": "AI",
    "MCP": "MCP",
    "LLM": "LLM",
    "URL": "URL",
    "SDK": "SDK",
    "TTL": "TTL",
}


class GofmtMissing(RuntimeError):
    pass


def go_name(const: str, override: str | None = None) -> str:
    if override:
        return override
    return "".join(INITIALISMS.get(part, part.capitalize()) for part in const.split("_"))


def kind_const(reg: Registry, kind: str) -> str:
    return reg.taxonomy["span_kind"]["names"][LANG] + INITIALISMS.get(kind, kind.capitalize())


def _literal(value: str) -> str:
    return json.dumps(value)


def render(reg: Registry) -> str:
    pre = reg.preamble
    al = reg.allowlists
    out: list[str] = []

    def name_of(const: str) -> str:
        return go_name(const, reg.row(const).get("go"))

    def ref_or_literal(key: str) -> str:
        const = reg.const_for_key(key, LANG)
        return name_of(const) if const is not None else _literal(key)

    out.append(GENERATED)
    out.append("//")
    out.extend(comment(pre["header"], "//"))
    out.append("")
    out.append(f"package {pre['go']['package']}")
    out.append("")

    out.append("const (")
    for i, row in enumerate(reg.rows(LANG)):
        if i and ("section" in row or "rationale" in row):
            out.append("")
        out.extend(comment(row.get("section"), "//", "\t"))
        out.extend(comment(row.get("rationale"), "//", "\t"))
        out.append(f"\t{go_name(row['const'], row.get('go'))} = {_literal(row['key'])}")
    out.append("")
    out.append("\t// Span kind values (openinference.span.kind).")
    for k in reg.taxonomy["span_kind"]["values"]:
        out.append(f"\t{kind_const(reg, k['name'])} = {_literal(k['name'])} // {k['doc']}")
    out.append(")")

    mp = reg.model_parameters
    out.append("")
    out.extend(comment(mp["doc"], "//"))
    out.append(f"var {mp['go']} = map[string]string{{")
    for spelling, target, note in reg.model_parameter_items():
        out.extend(comment(note, "//", "\t"))
        out.append(f"\t{_literal(spelling)}: {ref_or_literal(target)},")
    out.append("}")

    def member_set(section: str, extra: list[str] | None = None) -> None:
        block = al[section]
        out.append("")
        out.extend(comment(block["doc"], "//"))
        out.append(f"var {block['go']} = map[string]struct{{}}{{")
        for m in reg.members(section, LANG):
            out.extend(comment(m.get("note"), "//", "\t"))
            lit = name_of(m["ref"]) if "ref" in m else _literal(m["key"])
            out.append(f"\t{lit}: {{}},")
        out.extend(extra or [])
        out.append("}")

    member_set("pending_identity")

    prefixes = al["pending_identity_prefixes"]
    out.append("")
    out.extend(comment(prefixes["doc"], "//"))
    refs = ", ".join(name_of(r) for r in prefixes["refs"])
    out.append(f"var {prefixes['go']} = []string{{{refs}}}")

    members = al["invocation_parameters_content_members"]
    out.append("")
    out.extend(comment(members["doc"], "//"))
    values = ", ".join(_literal(v) for v in members["values"])
    out.append(f"var {members['go']} = []string{{{values}}}")

    # Go has no package-level comprehension, so the derived content keys are
    # expanded here. The registry is still their only source.
    derived = al["content"].get("derived")
    extra: list[str] = []
    if derived:
        extra.extend(comment(derived.get("note"), "//", "\t"))
        for prefix in derived["prefixes"]:
            for member in al["invocation_parameters_content_members"]["values"]:
                extra.append(f"\t{name_of(prefix)} + {_literal(member)}: {{}},")
    member_set("content", extra)

    for section in ("content_prefixes", "content_suffixes"):
        block = al[section]
        out.append("")
        out.extend(comment(block["doc"], "//"))
        out.append(f"var {block['go']} = []string{{")
        out.extend(f"\t{_literal(v)}," for v in block["values"])
        out.append("}")

    for name, key_fmt, value_fmt in (
        ("operation_by_kind", "kind", "literal"),
        ("kind_by_operation", "literal", "kind"),
        ("name_target_by_kind", "kind", "ref"),
    ):
        table = reg.table(name, LANG)
        if table is None:
            continue
        out.append("")
        out.extend(comment(table["doc"], "//"))
        out.append(f"var {table['names'][LANG]} = map[string]string{{")
        for k, v in table["map"].items():
            key = kind_const(reg, k) if key_fmt == "kind" else _literal(k)
            if value_fmt == "kind":
                value = kind_const(reg, v)
            elif value_fmt == "ref":
                value = name_of(v)
            else:
                value = _literal(v)
            out.append(f"\t{key}: {value},")
        out.append("}")

    return gofmt("\n".join(out) + "\n")


def gofmt(source: str) -> str:
    binary = shutil.which("gofmt")
    if binary is None:
        raise GofmtMissing("gofmt is required to generate Go; install Go or put gofmt on PATH")
    return subprocess.run([binary], input=source, capture_output=True, text=True, check=True).stdout
