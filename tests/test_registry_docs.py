"""docs/registry/ and out/docs-site/: the attribute reference
generators/registry_docs.py writes, for this repository and for the docs site.

Whether the committed pages are what Weaver renders is CI's weaver job
(`python -m generators.registry_docs --check`), and whether the site pages
compile as MDX is the test job's tools/mdx/check.mjs; these check what the
pages must hold, and the stale check itself, without Weaver.
"""

from __future__ import annotations

import json
import re

import pytest
import yaml

from conftest import ROOT
from generators import registry_docs

DOCS = ROOT / "docs" / "registry"
SITE = ROOT / "out" / "docs-site"
HEADER = "<!-- AUTOGENERATED, DO NOT EDIT."
SITE_HEADER = "{/* GENERATED FILE, do not edit by hand.\n"
MARKER = "x-release-please-version"
VERSION = re.compile(r"\b\d+\.\d+\.\d+(-[\w.]+)?(\+[-\w.]+)?\b")


def pages() -> dict[str, str]:
    return {p.name: p.read_text() for p in sorted(DOCS.glob("*.md"))}


def model_entries():
    """(key, defined here, template) for every attribute, ref and event in model/."""
    for f in sorted((ROOT / "model").rglob("*.yaml")):
        doc = yaml.safe_load(f.read_text()) or {}
        for a in doc.get("attributes") or []:
            yield a["key"], True, str(a["type"]).startswith("template[")
        for e in doc.get("events") or []:
            yield e["name"], True, False
        for g in doc.get("attribute_groups") or []:
            for a in g.get("attributes") or []:
                if "ref" in a:
                    yield a["ref"], False, False


def documented(text: str) -> set[str]:
    return set(re.findall(r"`([^`\s]+)`", text))


def test_every_page_is_marked_generated():
    assert pages()
    for name, text in pages().items():
        assert text.startswith(HEADER), name


def test_every_key_in_the_registry_is_on_a_page():
    keys = set().union(*(documented(t) for t in pages().values()))
    templates = {key for key, _, template in model_entries() if template}
    for key, _, _ in model_entries():
        assert (f"{key}.<key>" if key in templates else key) in keys, key


def test_a_rius_key_is_documented_on_its_namespace_page():
    for key, defined, template in model_entries():
        if defined and key.startswith(("rius.", "glassflow.")):
            page = pages()[key.split(".")[0] + ".md"]
            assert (f"{key}.<key>" if template else key) in documented(page), key


def test_upstream_keys_link_to_their_definitions_instead_of_restating_them():
    upstream = pages()["upstream.md"]
    defined = {key for key, here, _ in model_entries() if here}
    for key in {key for key, here, _ in model_entries() if not here} - defined:
        assert re.search(rf"\[`{re.escape(key)}`\]\(https://github\.com/open-telemetry/", upstream)


def test_namespace_pages_hold_only_keys_defined_here():
    defined = {key for key, here, _ in model_entries() if here}
    for name, text in pages().items():
        if name in {"README.md", "upstream.md", "normalizer-inputs.md"}:
            continue
        rows = re.findall(r"^\| <a id=\"[^\"]+\"></a>`([^`]+)`", text, flags=re.M)
        assert rows, name
        for key in rows:
            assert key.removesuffix(".<key>") in defined, (name, key)


def test_the_namespace_exceptions_say_why():
    for name, key in (("mcp.md", "mcp.result_type"), ("gen_ai.md", "gen_ai.first_token")):
        text = pages()[name]
        assert f"`{key}`" in text
        assert "Namespace exception:" in text


def site_pages() -> dict[str, str]:
    """slug -> page.mdx text; the index is ""."""
    return {
        p.parent.relative_to(SITE).as_posix().removeprefix("."): p.read_text()
        for p in sorted(SITE.rglob("page.mdx"))
    }


def slug(md_name: str) -> str:
    return "" if md_name == "README.md" else md_name.removesuffix(".md").replace("_", "-")


@pytest.mark.parametrize(
    "page,key,replacement",
    [
        ("glassflow", "glassflow.span.pending", "[`rius.span.pending`]({}rius#rius-span-pending)"),
        (
            "rius",
            "rius.main_agent.name",
            "[`gen_ai.main_agent.name`]({}upstream#gen-ai-main-agent-name)",
        ),
    ],
)
def test_a_deprecated_key_links_its_replacement(page, key, replacement):
    # A rename names its successor in Weaver's renamed_to; a key that moved
    # upstream (reason uncategorized) in the row's replaced_by.
    anchor = f'<a id="{key.replace(".", "-").replace("_", "-")}"></a>'
    md = pages()[f"{page}.md"].replace(anchor, "")
    assert f"| `{key}` | string | " in md or f"| `{key}` | boolean | " in md
    link = replacement.format("")
    md_link = re.sub(r"\]\((\w[\w-]*)#", r"](\1.md#", link)
    assert md_link in md, md_link
    site = site_pages()[page]
    assert replacement.format("/rius/interoperability/registry/") in site
    assert "uncategorized" not in site


def test_every_page_is_on_the_site():
    assert set(site_pages()) == {slug(name) for name in pages()}


def test_every_site_page_is_marked_generated_with_the_release():
    version = (ROOT / "version.txt").read_text().strip()
    for name, text in site_pages().items():
        body = re.sub(r"\A---\n.*?\n---\n\n", "", text, flags=re.S)
        assert body.startswith(SITE_HEADER), name
        source = f"Source of truth: registry/ in glassflow/rius-semconv (rius-semconv {version})."
        assert source in body.split("*/}", 1)[0], name
        # release-please's generic updater moves the first version on every
        # line carrying the marker, so each such line has exactly one.
        marked = [line for line in text.splitlines() if MARKER in line]
        assert len(marked) == 2, name
        for line in marked:
            assert [m.group(0) for m in VERSION.finditer(line)] == [version], (name, line)


def test_release_please_moves_the_version_of_every_site_page():
    config = json.loads((ROOT / "release-please-config.json").read_text())
    extra = set(config["packages"]["."]["extra-files"])
    for p in SITE.rglob("page.mdx"):
        assert p.relative_to(ROOT).as_posix() in extra, p


def test_site_pages_link_each_other_under_the_site_base_not_as_files():
    for name, text in site_pages().items():
        assert not re.search(r"\]\((?!https://)[^)]*\.md(#[^)]*)?\)", text), name
        assert "<!--" not in text, name
        for target in re.findall(r"\]\((/[^)#]*)", text):
            if target.startswith("/rius/interoperability/registry"):
                rest = target.removeprefix("/rius/interoperability/registry").lstrip("/")
                assert rest in site_pages(), (name, target)


def test_the_site_index_is_a_section_index_and_the_navigation_lists_every_page():
    assert site_pages()[""].startswith("---\nasIndexPage: true\n---\n")
    meta = (SITE / "_meta.tsx").read_text()
    keys = re.findall(r"'([^']+)'\s*:", meta)
    assert sorted(keys) == sorted(s for s in site_pages() if s)


def test_the_readme_links_every_page():
    readme = (ROOT / "README.md").read_text()
    for name in pages():
        assert f"docs/registry/{name}" in readme, name


@pytest.fixture
def docs(tmp_path):
    (tmp_path / "a.md").write_text("one\n")
    (tmp_path / "old.md").write_text("gone\n")
    return tmp_path


def test_stale_reports_a_changed_a_missing_and_a_leftover_page(docs, monkeypatch):
    monkeypatch.setattr(registry_docs, "ROOT", docs.parent)
    diffs = registry_docs.stale({"a.md": "two\n", "new.md": "x\n"}, docs)
    assert len(diffs) == 3
    assert any("-gone" in d for d in diffs)
    assert registry_docs.stale({"a.md": "one\n", "old.md": "gone\n"}, docs) == []


def test_write_replaces_the_pages_and_drops_leftovers(docs):
    registry_docs.write({"a.md": "two\n"}, docs)
    assert {p.name: p.read_text() for p in docs.iterdir()} == {"a.md": "two\n"}
