"""Write the Weaver registry under model/ from the YAML under registry/.

    python tools/to_weaver.py            write model/ and templates/params.yaml
    python tools/to_weaver.py --check    exit 1 if they differ from what would be written

registry/ stays the source of truth: edit it, then run this. CI runs --check,
so a registry change and its Weaver files land together. model/manifest.yaml
is not written here; it is maintained by hand (see tools/check_weaver_pins.py).

How a row maps (the Weaver mapping decisions, in short):

- An `origin: rius` attribute becomes a definition/2 attribute in
  model/rius/registry.yaml: key, type (`json` becomes `any`), brief, note (the
  rationale), stability, examples, deprecated. A `prefix` row under rius.*
  becomes a `template[...]` attribute without the trailing dot. A rius event
  becomes an `events:` entry.
- Every column rides the `rius` annotation (the key and rationale too), so
  the templates under templates/registry/ rebuild each row from the
  resolved registry.
- `retired:` rows become deprecated attributes with
  `code_generation: exclude`.
- An upstream key (`origin: otel`, or a row with `upstream`) is never
  redefined: it is a `ref` in the public group `rius.upstream`
  (model/rius/upstream.yaml), with its requirement level and our columns,
  rationale included, in the `rius` annotation. Enumerated values ride the
  ref as `values`. `passthrough:` keys are refs in `rius.passthrough`.
- OpenInference attributes no upstream registry defines are defined in
  model/inputs/openinference.yaml, in `rius.openinference` when the SDKs emit
  them and `rius.normalizer_input.openinference` when they only read them.
- The usage keys registry/usage_keys.yaml decides that no convention defines
  are defined in model/inputs/<producer>.yaml, in
  `rius.normalizer_input.<producer>`, with the decision in the
  `normalizer_input` part of the annotation. The ones under gen_ai.*, which
  only OpenTelemetry may define, go to the params sidecar instead.
- Rows Weaver has no definition for (the scope name, span names, key
  fragments, prefixes in namespaces we do not own, the events we only read)
  are kept whole in the params sidecar, templates/params.yaml, under
  `layout`, which also records every row's emission order. The sidecar
  carries the other registry files for `weaver registry generate --params`,
  unchanged except that each taxonomy table's `map` is a list of [key, value]
  pairs: Weaver sorts mapping keys, and the generated tables keep the
  registry's order.
"""

from __future__ import annotations

import argparse
import pathlib
import sys
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from generators import usage_keys  # noqa: E402
from generators.registry import Registry, defined_here, load_data, referenced  # noqa: E402

MODEL = ROOT / "model"
PARAMS = ROOT / "templates" / "params.yaml"
# The directories this tool owns. A file in them that it does not write is
# stale and fails --check.
OWNED_DIRS = (MODEL / "rius", MODEL / "inputs")

HEADER = "# Generated by tools/to_weaver.py from registry/. Edit registry/ and rerun it.\n"

# Weaver types. Everything else maps 1:1.
TYPES = {"json": "any"}
# Columns only Weaver's own fields carry. Every other column, the key and the
# rationale included, rides the `rius` annotation, so the templates can rebuild
# each registry row exactly from the resolved registry.
WEAVER_COLUMNS = {"brief", "examples", "stability", "deprecated"}
LEVELS = {"required", "recommended", "opt_in"}
GROUP = {"visibility": "public", "stability": "development"}


class Literal(str):
    """A multi-line string, dumped in block style."""


yaml.SafeDumper.add_representer(
    Literal, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|")
)


def literal(value: Any) -> Any:
    if isinstance(value, str) and "\n" in value:
        return Literal(value)
    if isinstance(value, dict):
        return {k: literal(v) for k, v in value.items()}
    if isinstance(value, list):
        return [literal(v) for v in value]
    return value


def dump(doc: Any) -> str:
    return yaml.safe_dump(literal(doc), sort_keys=False, allow_unicode=True, width=1000)


def annotation(row: dict) -> dict:
    out = {k: v for k, v in row.items() if k not in WEAVER_COLUMNS}
    if row.get("type") == "json":
        out["wire_type"] = "json"
    return out


def note(row: dict) -> str | None:
    text = row.get("rationale")
    upstream = row.get("upstream_equivalent")
    if upstream:
        line = (
            f"The OpenTelemetry GenAI conventions now define `{upstream}`\n"
            "for the same fact. A move to it is planned; until then this key is\n"
            "emitted and is not deprecated.\n"
        )
        text = f"{text.rstrip()}\n\n{line}" if text else line
    return text


def deprecated(row: dict) -> dict | None:
    d = row.get("deprecated")
    if d is None:
        return None
    out = {"reason": d["reason"]}
    if "renamed_to" in d:
        out["renamed_to"] = d["renamed_to"]
    out["note"] = d["note"]
    return out


def members(table: dict) -> dict:
    """A taxonomy table's values as a Weaver enum."""
    return {
        "members": [
            {
                "id": v["name"].lower(),
                "value": v["name"],
                "brief": v["doc"],
                "stability": "development",
            }
            for v in table["values"]
        ]
    }


def own_attribute(row: dict, taxonomy: dict | None = None) -> dict:
    prefix = row["symbol"] == "prefix"
    type_ = TYPES.get(row.get("type", "any"), row.get("type", "any"))
    if "values_from" in row and taxonomy is not None:
        type_ = members(taxonomy[row["values_from"]])
    attr: dict[str, Any] = {
        "key": row["key"].rstrip(".") if prefix else row["key"],
        "type": f"template[{type_}]" if prefix else type_,
        "brief": row["brief"],
    }
    if (text := note(row)) is not None:
        attr["note"] = text
    attr["stability"] = row["stability"]
    if "examples" in row:
        attr["examples"] = row["examples"]
    if (d := deprecated(row)) is not None:
        attr["deprecated"] = d
    attr["annotations"] = {"rius": annotation(row)}
    return attr


def retired_attribute(row: dict) -> dict:
    attr = own_attribute(row)
    attr["annotations"] = {"code_generation": {"exclude": True}, **attr["annotations"]}
    return attr


def own_event(row: dict) -> dict:
    event: dict[str, Any] = {"name": row["key"], "brief": row["brief"]}
    if (text := note(row)) is not None:
        event["note"] = text
    event["stability"] = row["stability"]
    event["requirement_level"] = "recommended"
    if (d := deprecated(row)) is not None:
        event["deprecated"] = d
    event["annotations"] = {"rius": annotation(row)}
    return event


def requirement_level(row: dict) -> Any:
    level = row.get("level")
    if level in LEVELS:
        return level
    if level == "conditionally_required":
        return {"conditionally_required": row.get("level_note", "when applicable")}
    return None  # vendor, or none: OpenTelemetry has no level to state


def ref(row: dict, values: dict[str, str]) -> dict:
    """A reference to an upstream key, carrying only our facts."""
    item: dict[str, Any] = {"ref": row["key"]}
    if (level := requirement_level(row)) is not None:
        item["requirement_level"] = level
    ann = dict(row)
    if values:
        ann["values"] = values
    item["annotations"] = {"rius": ann}
    return item


PRODUCER_BRIEF = {
    "mapped": "Usage count written by {name}; the {by} {normalizers} {verb} it to {target}.",
    "ignored": "Usage figure written by {name}, left on the span: nothing reads it as usage.",
    "not_usage": "Key written by {name} that names tokens or cost but is not a usage count.",
    "gap": "Usage count written by {name} that reaches no canonical key yet.",
}


def brief_for(entry: dict, name: str) -> str:
    by = entry.get("mapped_by", [])
    return PRODUCER_BRIEF[entry["decision"]].format(
        name=name,
        by=" and ".join([", ".join(by[:-1]), by[-1]] if len(by) > 1 else by),
        normalizers="normalizers" if len(by) > 1 else "normalizer",
        verb="map" if len(by) > 1 else "maps",
        target=entry.get("target"),
    )


def input_attribute(entry: dict, producer: str, spec: dict) -> dict:
    """A usage key another producer writes, as a definition with its decision."""
    prefix = "prefix" in entry
    name = usage_keys.entry_name(entry)
    type_ = entry.get("type", "any" if prefix else "int")
    decision = {k: v for k, v in entry.items() if k not in {"key", "prefix", "type", "reason"}}
    attr: dict[str, Any] = {
        "key": entry["prefix"].rstrip(".") if prefix else name,
        "type": f"template[{type_}]" if prefix else type_,
        "brief": brief_for(entry, spec["name"]),
    }
    if entry.get("reason"):
        attr["note"] = entry["reason"]
    attr["stability"] = "development"
    attr["annotations"] = {
        "rius": {"producer": producer, "direction": "read", "normalizer_input": decision}
    }
    return attr


def group(id_: str, brief: str, keys: list[str]) -> dict:
    return {"id": id_, **GROUP, "brief": brief, "attributes": [{"ref": k} for k in keys]}


def definitions(groups: list[dict], attributes: list[dict], events=None) -> str:
    doc: dict[str, Any] = {"file_format": "definition/2", "attribute_groups": groups}
    doc["attributes"] = attributes
    if events is not None:
        doc["events"] = events
    return HEADER + "\n" + dump(doc)


def ordered_maps(taxonomy: dict) -> dict:
    """The taxonomy with each table's `map` as a list of [key, value] pairs.
    Weaver hands mappings to the templates with their keys sorted, and the
    generated tables keep the registry's order."""
    out = {}
    for name, table in taxonomy.items():
        table = dict(table)
        if isinstance(table.get("map"), dict):
            table["map"] = [[k, v] for k, v in table["map"].items()]
        out[name] = table
    return out


def render(data: dict) -> dict[pathlib.Path, str]:
    """Every file this tool owns, path -> content."""
    registry = Registry(data)
    rows = registry.attributes
    taxonomy = data["taxonomy"]
    in_model = {r["const"] for r in rows if defined_here(r) or referenced(r)}
    values: dict[str, dict[str, str]] = {}
    for r in rows:
        if r["symbol"] == "value" and r.get("of") in in_model:
            values.setdefault(r["of"], {})[r["const"]] = r["key"]

    own, events, refs, openinference, layout = [], [], [], [], []
    for r in rows:
        if r["const"] in in_model:
            if referenced(r):
                refs.append(ref(r, values.get(r["const"], {})))
            elif r["symbol"] == "event":
                events.append(own_event(r))
            elif r["origin"] == "openinference":
                openinference.append(own_attribute(r, taxonomy))
            else:
                own.append(own_attribute(r))
            layout.append({"const": r["const"]})
        elif r["symbol"] == "value" and r.get("of") in in_model:
            # Enumerated values ride their parent ref as `values`; the row
            # itself stays whole here, with its own prose.
            layout.append(r)
        else:
            # No Weaver definition: keep the whole row.
            layout.append(r)
    retired = [retired_attribute(r) for r in registry.retired]
    passthrough = [
        {"ref": r["key"], "annotations": {"rius": {k: v for k, v in r.items() if k != "key"}}}
        for r in registry.passthrough
    ]

    # Usage keys no convention defines, by producer; the gen_ai.* ones stay
    # out of the Weaver registry.
    uk = data["usage_keys"]
    registry_keys = {r["key"] for r in rows}
    inputs: dict[str, list[dict]] = {p: [] for p in uk.get("producers") or {}}
    sidecar_inputs = []
    for entry in uk["keys"]:
        name = usage_keys.entry_name(entry)
        if entry["decision"] == "canonical" or name in registry_keys:
            continue
        producer = usage_keys.producer_for(uk, name)
        if producer is None:
            sidecar_inputs.append(entry)
        else:
            inputs[producer].append(input_attribute(entry, producer, uk["producers"][producer]))

    emitted = [a for a in openinference if a["annotations"]["rius"].get("direction") != "read"]
    read = [a for a in openinference if a["annotations"]["rius"].get("direction") == "read"]
    inputs["openinference"] = read + inputs.get("openinference", [])

    files = {
        MODEL / "rius" / "registry.yaml": definitions(
            [
                group(
                    "registry.rius",
                    "Attributes in the rius namespace, and the Rius keys outside it.",
                    [a["key"] for a in own + retired],
                )
            ],
            own + retired,
            events,
        ),
        MODEL / "rius" / "upstream.yaml": HEADER
        + "\n"
        + dump(
            {
                "file_format": "definition/2",
                "attribute_groups": [
                    {
                        "id": "rius.upstream",
                        **GROUP,
                        "brief": "OpenTelemetry attributes the Rius SDKs emit or read.",
                        "attributes": refs,
                    },
                    {
                        "id": "rius.passthrough",
                        **GROUP,
                        "brief": "OpenTelemetry attributes other producers write that "
                        "Rius stores but no Rius SDK emits.",
                        "attributes": passthrough,
                    },
                ],
            }
        ),
    }
    for producer, attrs in inputs.items():
        spec = (uk.get("producers") or {}).get(producer, {"name": "OpenInference"})
        groups = []
        if producer == "openinference":
            groups.append(
                group(
                    "rius.openinference",
                    "OpenInference attributes the Rius SDKs emit.",
                    [a["key"] for a in emitted],
                )
            )
        groups.append(
            group(
                f"rius.normalizer_input.{producer}",
                f"Attributes {spec['name']} writes that the Rius normalizers read.",
                [a["key"] for a in attrs],
            )
        )
        defined = emitted + attrs if producer == "openinference" else attrs
        files[MODEL / "inputs" / f"{producer}.yaml"] = definitions(groups, defined)

    params = {
        "params": {
            "layout": layout,
            "normalizer_inputs": sidecar_inputs,
            "allowlists": data["allowlists"],
            "taxonomy": ordered_maps(data["taxonomy"]),
            "model_parameters": data["model_parameters"],
            "preamble": data["preamble"],
        }
    }
    files[PARAMS] = (
        HEADER
        + "# The weaver --params file: emission order and what Weaver has no definition for.\n"
        + dump(params)
    )
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the files are stale")
    args = parser.parse_args(argv)

    data = load_data()
    errors = Registry(data).lint()
    if errors:
        print("registry lint failed; nothing written:")
        for e in errors:
            print(f"  {e}")
        return 1
    files = render(data)
    stale = sorted(p for d in OWNED_DIRS if d.is_dir() for p in d.glob("*.yaml") if p not in files)

    if args.check:
        changed = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        for p in changed + stale:
            print(f"stale: {p.relative_to(ROOT)}")
        if changed or stale:
            print("model/ is stale. Run 'python tools/to_weaver.py' and commit the result.")
            return 1
        print("model/: up to date")
        return 0

    for p in stale:
        p.unlink()
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"wrote {len(files)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
